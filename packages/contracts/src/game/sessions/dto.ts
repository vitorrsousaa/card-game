import { z } from "zod";

export const CreateSessionInputSchema = z.object({
	userId: z.string().uuid("User ID is required"),
});

export type CreateSessionInput = z.infer<typeof CreateSessionInputSchema>;

export const CreateSessionRequestSchema = z.object({});

export type CreateSessionRequest = z.infer<typeof CreateSessionRequestSchema>;

export const GetSessionInputSchema = z.object({
	sessionId: z.string().uuid("Session ID must be a valid UUID"),
});

export type GetSessionInput = z.infer<typeof GetSessionInputSchema>;

export const CreateSessionOutputSchema = z.object({
	session: z.object({
		id: z.string().uuid("Session ID is required"),
		userId: z.string().uuid("User ID is required"),
		createdAt: z.date({ message: "Created at is required" }),
		updatedAt: z.date({ message: "Updated at is required" }),
	}),
});

/** Create session API response. Same shape as GetSessionResponseDto (SessionDto). */
export type CreateSessionOutput = { session: SessionDto };

/** Get session API response. Same format as CreateSessionOutput. */
export type GetSessionOutput = { session: SessionDto };

/**
 * Player state in a game session
 */
export interface PlayerDto {
	life: number;
	maxLife: number;
	mana: number;
	maxMana: number;
	hand: string[]; // card IDs
	deck: string[]; // card IDs
	board: string[]; // card IDs
}

/**
 * Full game state from the Lua engine
 */
export interface GameStateDto {
	sessionId: string;
	turn: number;
	phase: string;
	players: PlayerDto[];
	currentPlayer?: number;
}

/**
 * Game events for animations/UI feedback
 */
export interface GameEventDto {
	type: string;
	payload?: Record<string, unknown>;
}

/**
 * Session DTO as stored in Redis/DynamoDB and returned by API.
 * Create Session (POST /sessions) and Get Session (GET /sessions/:sessionId) both return this same format.
 */
export interface SessionDto {
	/** Session ID (generated by Lua engine on init) */
	id: string;
	/** Full game state from the Lua engine */
	state: GameStateDto;
	/** Events generated in the last action */
	// events: GameEventDto[];
	/** User ID who owns this session */
	userId: string | null;
	/** When the session was created */
	createdAt: string; // ISO string
	/** Last update timestamp */
	updatedAt: string; // ISO string
}

/**
 * Create session response (API output). Same as SessionDto.
 */
export type CreateSessionResponseDto = SessionDto;

/**
 * Get session response (API output). Create and Get Session return the same SessionDto format.
 */
export type GetSessionResponseDto = SessionDto;
